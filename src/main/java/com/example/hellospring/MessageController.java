package com.example.hellospring;

import jakarta.validation.Valid;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;
import org.springframework.http.HttpStatus;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.ResponseStatus;
import org.springframework.web.bind.annotation.RestController;

import java.util.List;

@RestController
public class MessageController {
    private final MessageService service;

    public MessageController(MessageService service) {
        this.service = service;
    }

    @GetMapping("/")
    public String hello() {
        return "Hello, World!";
    }

    @GetMapping("/messages")
    public List<Message> getMessages() {
        return service.getAllMessages();
    }

    @PostMapping("/messages")
    @ResponseStatus(HttpStatus.CREATED)
    public Message createMessage(@Valid @RequestBody CreateMessageRequest request) {
        return service.createMessage(request.content(), request.author());
    }

    /** IDs are generated by the repository and cannot be chosen through this API. */
    public record CreateMessageRequest(
            @NotBlank(message = "Содержимое обязательно")
            @Size(max = 2000, message = "Содержимое: не более 2000 символов") String content,
            @NotBlank(message = "Автор обязателен")
            @Size(max = 100, message = "Автор: не более 100 символов") String author) {
    }
}
